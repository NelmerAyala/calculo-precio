-- Función que retorna solicitudes EN_PROCESO con error transitorio
-- Si @P_APROBADOR_EMAIL = NULL: retorna TODAS las solicitudes pendientes
-- Si @P_APROBADOR_EMAIL != NULL: filtra por aprobador específico
