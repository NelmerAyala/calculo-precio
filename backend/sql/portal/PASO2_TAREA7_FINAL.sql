SELECT
  ID_SOLICITUD,
  CODIGO_SOLICITUD,
  REINTENTOS_TOTALES,
  REPROCESOS_AUTORIZADOS,
  ULTIMA_ACCION,
  FECHA_ULTIMA_ACCION,
  ULTIMA_ACCION_POR_NOMBRE
FROM PORTAL_PRECIOS.FN_OBTENER_BANDEJA_APROBACION('aprobador@intelix.com')
WHERE REPROCESOS_AUTORIZADOS > 0
ORDER BY FECHA_ULTIMA_ACCION DESC;

