/*
  Interpretación corregida a partir de los ejemplos aclarados:

  1. El tramo se selecciona usando el PRECIO_CALCULADO sin redondeo comercial.
  2. Para terminales de tipo sufijo se conserva el bloque del precio:
       10,16  -> bloque 10 + terminales ,49/,99 -> 10,49
       13,195 -> bloque 13 + terminales ,49/,99 -> 13,49
  3. Se escoge el candidato más cercano dentro de ese bloque.
  4. En empate se escoge el candidato superior.
  5. @EXTENDER_MAYOR_100000=0 respeta el máximo documental de 100.000.
     Con valor 1, continúa el patrón 50/90 para precios mayores; requiere
     aprobación funcional porque el anexo no define ese rango.
*/
CREATE OR ALTER FUNCTION COFER.FN_REDONDEAR_PRECIO
(
    @PRECIO DECIMAL(28,8),
    @EXTENDER_MAYOR_100000 BIT
)
RETURNS TABLE
WITH SCHEMABINDING
AS
RETURN
(
    WITH BANDAS AS
    (
      SELECT * FROM (VALUES
       (1,CAST(0 AS DECIMAL(28,8)),CAST(0.50 AS DECIMAL(28,8)),'E',CAST(0.01 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (2,CAST(0.50 AS DECIMAL(28,8)),CAST(1.00 AS DECIMAL(28,8)),'E',CAST(0.05 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (3,CAST(1.00 AS DECIMAL(28,8)),CAST(2.50 AS DECIMAL(28,8)),'E',CAST(0.10 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (4,CAST(2.50 AS DECIMAL(28,8)),CAST(4.75 AS DECIMAL(28,8)),'E',CAST(0.25 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (5,CAST(4.75 AS DECIMAL(28,8)),CAST(5.15 AS DECIMAL(28,8)),'F',CAST(0 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (6,CAST(5.15 AS DECIMAL(28,8)),CAST(10.15 AS DECIMAL(28,8)),'C',CAST(0 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (7,CAST(10.15 AS DECIMAL(28,8)),CAST(50.24 AS DECIMAL(28,8)),'C',CAST(0 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (8,CAST(50.24 AS DECIMAL(28,8)),CAST(99.99 AS DECIMAL(28,8)),'C',CAST(0 AS DECIMAL(28,8)),CAST(1 AS DECIMAL(28,8))),
       (9,CAST(99.99 AS DECIMAL(28,8)),CAST(500 AS DECIMAL(28,8)),'C',CAST(0 AS DECIMAL(28,8)),CAST(10 AS DECIMAL(28,8))),
       (10,CAST(500 AS DECIMAL(28,8)),CAST(1000 AS DECIMAL(28,8)),'C',CAST(0 AS DECIMAL(28,8)),CAST(10 AS DECIMAL(28,8))),
       (11,CAST(1000 AS DECIMAL(28,8)),CAST(5000 AS DECIMAL(28,8)),'C',CAST(0 AS DECIMAL(28,8)),CAST(100 AS DECIMAL(28,8))),
       (12,CAST(5000 AS DECIMAL(28,8)),CAST(100000 AS DECIMAL(28,8)),'C',CAST(0 AS DECIMAL(28,8)),CAST(100 AS DECIMAL(28,8)))
      ) B(TRAMO,DESDE_EXCLUSIVO,HASTA,MODO,PASO,PERIODO)
    ),
    BANDA AS
    (
      SELECT TOP (1) B.*
      FROM BANDAS B
      WHERE @PRECIO>B.DESDE_EXCLUSIVO
        AND
        (
          @PRECIO<=B.HASTA
          OR (B.TRAMO=12 AND @EXTENDER_MAYOR_100000=1 AND @PRECIO>100000)
        )
      ORDER BY B.TRAMO
    ),
    TERMINALES AS
    (
      SELECT * FROM (VALUES
       (6,CAST(0.29 AS DECIMAL(28,8))),(6,CAST(0.49 AS DECIMAL(28,8))),
       (6,CAST(0.69 AS DECIMAL(28,8))),(6,CAST(0.99 AS DECIMAL(28,8))),
       (7,CAST(0.49 AS DECIMAL(28,8))),(7,CAST(0.99 AS DECIMAL(28,8))),
       (8,CAST(0.99 AS DECIMAL(28,8))),
       (9,CAST(3 AS DECIMAL(28,8))),(9,CAST(5 AS DECIMAL(28,8))),
       (9,CAST(7 AS DECIMAL(28,8))),(9,CAST(9 AS DECIMAL(28,8))),
       (10,CAST(0 AS DECIMAL(28,8))),(10,CAST(5 AS DECIMAL(28,8))),
       (11,CAST(30 AS DECIMAL(28,8))),(11,CAST(50 AS DECIMAL(28,8))),
       (11,CAST(70 AS DECIMAL(28,8))),(11,CAST(90 AS DECIMAL(28,8))),
       (12,CAST(50 AS DECIMAL(28,8))),(12,CAST(90 AS DECIMAL(28,8)))
      ) T(TRAMO,TERMINAL)
    ),
    CANDIDATOS AS
    (
      SELECT B.TRAMO,
             CAST(CEILING(@PRECIO/NULLIF(B.PASO,0))*B.PASO AS DECIMAL(28,8)) VALOR
      FROM BANDA B WHERE B.MODO='E'

      UNION ALL
      SELECT B.TRAMO,CAST(4.99 AS DECIMAL(28,8))
      FROM BANDA B WHERE B.MODO='F'

      UNION ALL
      SELECT B.TRAMO,
             CAST(FLOOR(@PRECIO/B.PERIODO)*B.PERIODO+T.TERMINAL AS DECIMAL(28,8))
      FROM BANDA B
      JOIN TERMINALES T ON T.TRAMO=B.TRAMO
      WHERE B.MODO='C'
    ),
    ELEGIDO AS
    (
      SELECT TOP (1) C.TRAMO,C.VALOR
      FROM CANDIDATOS C
      WHERE C.VALOR>0
      ORDER BY ABS(C.VALOR-@PRECIO),C.VALOR DESC
    )
    SELECT
      CAST(E.VALOR AS DECIMAL(28,8)) PRECIO_REDONDEADO,
      E.TRAMO,
      CAST(CASE
        WHEN @PRECIO IS NULL OR @PRECIO<=0 THEN 'PRECIO_INVALIDO'
        WHEN E.VALOR IS NULL THEN 'FUERA_RANGO'
        ELSE 'OK' END AS VARCHAR(20)) ESTADO
    FROM (VALUES(1)) X(N)
    LEFT JOIN ELEGIDO E ON 1=1
);
GO

/* Pruebas de aceptación de la interpretación corregida. */
DECLARE @CASOS TABLE
(
  PRECIO DECIMAL(28,8),
  ESPERADO DECIMAL(28,8),
  EXTENDER BIT
);

INSERT @CASOS VALUES
(10.15,10.29,0),(10.16,10.49,0),(13.195,13.49,0),
(50.24,50.49,0),(50.25,50.99,0),(100,103,0),
(501,500,0),(1001,1030,0),(5001,5050,0),
(100000.01,NULL,0),(125000,125050,1);

IF EXISTS
(
  SELECT 1
  FROM @CASOS C
  CROSS APPLY COFER.FN_REDONDEAR_PRECIO(C.PRECIO,C.EXTENDER) R
  WHERE EXISTS
  (
    SELECT C.ESPERADO
    EXCEPT
    SELECT R.PRECIO_REDONDEADO
  )
)
  THROW 51200,'La función no produjo los resultados esperados.',1;

SELECT C.*,R.PRECIO_REDONDEADO,R.TRAMO,R.ESTADO
FROM @CASOS C
CROSS APPLY COFER.FN_REDONDEAR_PRECIO(C.PRECIO,C.EXTENDER) R;
GO
